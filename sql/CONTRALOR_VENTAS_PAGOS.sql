-- Registro de pagos (abonos) por venta, permite pagos parciales.
CREATE TABLE IF NOT EXISTS CONT_VENTA_PAGO (
    ID_PAGO INT AUTO_INCREMENT PRIMARY KEY,
    ID_VENTA INT NOT NULL,
    FECHA_PAGO DATE NOT NULL,
    FORMA_PAGO VARCHAR(20) NOT NULL DEFAULT 'DEPOSITO', -- EFECTIVO | DEPOSITO | CHEQUE
    MONTO DECIMAL(12,2) NOT NULL,
    REFERENCIA VARCHAR(300) NULL,
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX IX_VENTA (ID_VENTA)
);
