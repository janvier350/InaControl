-- Secuencia de Pesos de Bascula
CREATE TABLE IF NOT EXISTS CONT_BASCULA_RANGO (
    ID_RANGO INT AUTO_INCREMENT PRIMARY KEY,
    DESDE INT NOT NULL,
    HASTA INT NOT NULL,
    OBSERVACION VARCHAR(300) NULL,
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS CONT_BASCULA_SECUENCIA (
    ID_SECUENCIA INT AUTO_INCREMENT PRIMARY KEY,
    NUMERO INT NOT NULL,
    ID_RANGO INT NULL,
    ESTADO VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE', -- PENDIENTE | USADO | ANULADO
    FECHA DATE NULL,
    PROVEEDOR_CLIENTE VARCHAR(200) NULL,
    PESO_BRUTO DECIMAL(10,2) NULL,
    TARA DECIMAL(10,2) NULL,
    PESO_NETO DECIMAL(10,2) NULL,
    OBSERVACION VARCHAR(300) NULL,
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_NUMERO (NUMERO)
);
