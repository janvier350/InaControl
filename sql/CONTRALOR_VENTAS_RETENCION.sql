-- Catalogo de Clientes + numero de factura y retencion en Ventas
CREATE TABLE IF NOT EXISTS CONT_CLIENTE (
    ID_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(200) NOT NULL,
    ESTADO VARCHAR(2) NOT NULL DEFAULT 'A',
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE CONT_VENTA
    ADD COLUMN FACTURA_NO VARCHAR(20) NULL AFTER CLIENTE,
    ADD COLUMN PORC_RETENCION DECIMAL(6,4) NOT NULL DEFAULT 0 AFTER TOTAL,
    ADD COLUMN VALOR_RETENCION DECIMAL(12,2) NOT NULL DEFAULT 0 AFTER PORC_RETENCION,
    ADD COLUMN TOTAL_A_COBRAR DECIMAL(14,2) NULL AFTER VALOR_RETENCION;
