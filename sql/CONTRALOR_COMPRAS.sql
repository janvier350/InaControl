-- Compras: boletas de bascula (ingreso de arroz) + liquidaciones (factura que agrupa boletas)

CREATE TABLE IF NOT EXISTS CONT_COMPRA_LIQUIDACION (
    ID_LIQUIDACION INT AUTO_INCREMENT PRIMARY KEY,
    FECHA DATE NOT NULL,
    PROVEEDOR VARCHAR(200) NOT NULL,
    FACTURA_NO VARCHAR(50) NULL,
    QQ_TOTAL DECIMAL(12,4) NOT NULL DEFAULT 0,
    PRECIO DECIMAL(12,4) NOT NULL DEFAULT 0,
    TOTAL DECIMAL(14,2) NOT NULL DEFAULT 0,
    OBSERVACION VARCHAR(300) NULL,
    ESTADO VARCHAR(2) NOT NULL DEFAULT 'A',
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS CONT_COMPRA_BOLETA (
    ID_BOLETA INT AUTO_INCREMENT PRIMARY KEY,
    FECHA DATE NOT NULL,
    PROVEEDOR VARCHAR(200) NOT NULL,
    ID_SECUENCIA INT NULL,
    NUMERO_BASCULA INT NULL,
    PESO_BRUTO DECIMAL(10,2) NOT NULL,
    TARA DECIMAL(10,2) NOT NULL,
    PESO_NETO DECIMAL(10,2) NOT NULL,
    QQ DECIMAL(12,4) NOT NULL,
    PORC_CALIFICACION DECIMAL(6,4) NOT NULL DEFAULT 0,
    QQ_CALIFICADO DECIMAL(12,4) NOT NULL DEFAULT 0,
    QQ_NETO DECIMAL(12,4) NOT NULL,
    ID_LIQUIDACION INT NULL,
    OBSERVACION VARCHAR(300) NULL,
    ESTADO VARCHAR(2) NOT NULL DEFAULT 'A',
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
